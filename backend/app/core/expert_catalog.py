def expert_seed_rows() -> list[tuple[str, str, str, str]]:
    """返回 (kind, name, description, payload_json) 种子行。"""
    import json

    rows: list[tuple[str, str, str, str]] = []
    for e in EXPERTS:
        payload = json.dumps({"domain": e["domain"],
                              "domain_label": DOMAINS[e["domain"]],
                              "department": e["department"],
                              "skills": e["skills"]},
                             ensure_ascii=False)
        rows.append(("expert", e["name"], e["description"], payload))
    for t in TEAMS:
        payload = json.dumps({"domain": t["domain"],
                              "domain_label": DOMAINS[t["domain"]],
                              "members": t["members"]},
                             ensure_ascii=False)
        rows.append(("team", t["name"], t["description"], payload))
    return rows
